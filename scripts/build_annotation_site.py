"""Generate the blind item file for the B1 annotation website.

The site must never receive a gold label: the annotator sees the two arguments
and picks a class.  ``sense_l1``/``l2``/``l3`` and any HIT relation code are
therefore dropped here rather than hidden in the UI, so they cannot leak
through the page source or the browser cache.

    python scripts/build_annotation_site.py \
        --packet data/processed/l1/b1_packet.jsonl \
        --out annotation/items.js
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from discourse_reliability.schema import load_items  # noqa: E402

TASK_ZH = {"explicit_sense": "显式", "implicit_relation": "隐式"}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--packet", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    items = load_items(args.packet)
    rows = []
    for it in items:
        rows.append({
            "id": it.id,
            "doc": it.doc_id,
            "split": it.meta.get("b1_split", "main"),
            "task": TASK_ZH.get(it.task, it.task),
            "arg1": it.arg1 or it.text,
            "arg2": it.arg2,
            "conn": it.connective,
            "text": it.text,
        })

    digest = hashlib.sha256(
        json.dumps([r["id"] for r in rows], sort_keys=True).encode()
    ).hexdigest()[:12]
    payload = {
        "packet": args.packet,
        "packet_hash": digest,
        "generated": date.today().isoformat(),
        "n": len(rows),
        "items": rows,
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// generated by scripts/build_annotation_site.py -- do not edit\n"
        f"window.B1 = {json.dumps(payload, ensure_ascii=False, indent=0)};\n",
        encoding="utf-8",
    )
    print(json.dumps(
        {"written": len(rows), "packet_hash": digest, "out": str(out)},
        ensure_ascii=False,
    ))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
